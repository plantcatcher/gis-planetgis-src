def extract():
    text = '\n'.join(p.extract_text() for p in pypdf.PdfReader(fetch(PDF, 'yyh.pdf')).pages)
    seg = text[text.index('表 2.1用地用海分类名称、代码'):text.index('2.2【城镇村及工矿用地分类】')]
    seg = re.sub(r'第 \d+ 页\n一级类 二级类 三级类\n代码 名称 代码 名称 代码 名称\n', '', seg)
    seg = seg.split('代码 名称 代码 名称 代码 名称\n', 1)[1]
    items = [(c, re.sub(r'\s+', '', n)) for c, n in
             re.findall(r'(\d{2,6})\s*\n?([^\d]+?)(?=\s*\d{2,6}\s|\s*$)', seg + ' ')]

    lines = text.split('\n')
    a = max(i for i, l in enumerate(lines) if l.strip() == '附录 A')
    b = max(i for i, l in enumerate(lines) if l.strip() == '附录 B')
    app = '\n'.join(lines[a:b])
    app = re.sub(r'第 \d+ 页\n(代码 名称 含义\n)?', '', app)
    pos, start = [], 0
    for c, _ in items:
        m = re.search(r'(?m)^' + c + r'(?!\d)', app[start:])
        pos.append(start + m.start())
        start += m.end()
    defs = {}
    for k, (c, n) in enumerate(items):
        end = pos[k + 1] if k + 1 < len(items) else len(app)
        s = re.sub(r'\s+', '', app[pos[k] + len(c):end])
        s = re.sub(r'第\d+页$', '', s)
        defs[c] = DEF_FIX.get(c) or (s[len(n):] if s.startswith(n) else s)
    return items, defs



# ── 校验 211 / 985 计数 ────────────────────────────────────────
n211 = sum(1 for x in U if x[4])
n985 = sum(1 for x in U if x[3])
nMili = sum(1 for x in U if x[5])
assert n985 == 39, "985 数量应为 39，实际 %d" % n985
assert n211 == 116, "211 数量应为 116，实际 %d" % n211
print("院校原始条目：%d（含 211=%d, 985=%d, 军校=%d）" % (len(U), n211, n985, nMili))

# ── 同城市抖散，避免点位重叠 ───────────────────────────────────
from collections import defaultdict
by_city = defaultdict(list)
for i, x in enumerate(U):
    by_city[x[1]].append(i)

features = []
seen = set()
prov_stat = defaultdict(lambda: {"total": 0, "n985": 0, "n211": 0, "nMili": 0, "name": ""})

for city, idxs in by_city.items():
    base = CITY[city]
    n = len(idxs)
    for k, i in enumerate(idxs):
        name, c, prov, s985, s211, mili = U[i]
        # 黄金角螺旋抖散
        ang = k * 2.399963
        r = 0.14 * math.sqrt(k)
        lng = base[0] + r * math.cos(ang)
        lat = base[1] + r * math.sin(ang)
        key = (name, prov)
        if key in seen:
            continue
        seen.add(key)
        rank = 3 if s985 else (2 if s211 else (1 if mili else 0))
        features.append({
            "type": "Feature",
            "geometry": {"type": "Point", "coordinates": [round(lng, 5), round(lat, 5)]},
            "properties": {
                "name": name, "city": city, "province": prov,
                "is985": s985, "is211": s211, "isMili": mili, "rank": rank
            }
        })
        ps = prov_stat[prov]
        ps["total"] = PROV_TOTAL.get(prov, 0)
        ps["name"] = prov
        ps["n985"] += s985
        ps["n211"] += s211
        ps["nMili"] += mili

print("去重后院校点位：%d" % len(features))

# ── 省级聚合 JSON（按教育部总数 + 精英分档）─────────────────────
provinces = []
for prov, ps in PROV_TOTAL.items():
    agg = prov_stat.get(prov, {"name": prov, "n985": 0, "n211": 0, "nMili": 0})
    provinces.append({
        "name": prov,
        "total": ps,
        "n985": agg.get("n985", 0),
        "n211": agg.get("n211", 0),
        "nMili": agg.get("nMili", 0),
        # 双一流（二轮）= 原 985 + 原 211，本数据集二者合并即 n211
        "nDouble": agg.get("n211", 0)
    })
provinces.sort(key=lambda x: -x["total"])

univ_fc = {"type": "FeatureCollection", "features": features}
with open(os.path.join(OUT_DIR, "universities.json"), "w", encoding="utf-8") as f:
    json.dump(univ_fc, f, ensure_ascii=False, separators=(",", ":"))

